export function normalizeLocale(value: string | null | undefined): Locale {
  const normalized = value?.toLowerCase();
  if (normalized?.startsWith("zh")) return "zh";
  if (normalized?.startsWith("es")) return "es";
  return "en";
}

export function translate(locale: Locale, key: TranslationKey, values?: Record<string, string | number>) {
  let message: string = dictionaries[locale][key];
  if (!values) return message;
  for (const [name, value] of Object.entries(values)) {
    message = message.replaceAll(`{${name}}`, String(value));
  }
  return message;
}

export function localeTag(locale: Locale) {
  return locale === "zh" ? "zh-CN" : locale === "es" ? "es-ES" : "en-US";
}

export function formatRelativeTime(locale: Locale, createdAt: string) {
  const deltaSeconds = Math.round((new Date(createdAt).getTime() - Date.now()) / 1000);
  const formatter = new Intl.RelativeTimeFormat(localeTag(locale), { numeric: "auto" });
  if (Math.abs(deltaSeconds) < 60) return formatter.format(deltaSeconds, "second");
  const minutes = Math.round(deltaSeconds / 60);
  if (Math.abs(minutes) < 60) return formatter.format(minutes, "minute");
  const hours = Math.round(minutes / 60);
  if (Math.abs(hours) < 24) return formatter.format(hours, "hour");
  return formatter.format(Math.round(hours / 24), "day");
}
